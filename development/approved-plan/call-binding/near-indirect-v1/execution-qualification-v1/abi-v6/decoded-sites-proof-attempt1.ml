let R1_SECRET_CALLER_EXEC = R1_NORMALIZE_EXEC_RULE(X86_MK_EXEC_RULE r1_secret_caller_mc);;
let R1_PUBLIC_CALLER_EXEC = R1_NORMALIZE_EXEC_RULE(X86_MK_EXEC_RULE r1_public_caller_mc);;
let R1_CALLER_EXEC_AT family off =
 let rule=match family with
 | 0->R1_SECRET_CALLER_EXEC | 1->R1_PUBLIC_CALLER_EXEC
 | 2->R1_CRYPTO_PLT_PREFIX_EXEC | 3->R1_CLEANSE_PLT_PREFIX_EXEC
 | 4->R1_MEMCMP_PLT_PREFIX_EXEC | _->failwith "unknown code family" in
 match (snd rule).(off) with Some th->th | None->failwith "instruction interior";;
