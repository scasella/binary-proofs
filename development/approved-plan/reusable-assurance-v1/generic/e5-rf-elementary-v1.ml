let E5_RF_COMPONENT_EXTENSIONALLY_VALID =
 EXTENSIONALLY_VALID_COMPONENT_CONV
 `extensionally_valid_component (rflags :> bitelement 16)`;;
let E5_RF_WRITE_READ =
 REWRITE_RULE[READ_COMPONENT_COMPOSE;READ_BITELEMENT]
 (CONJUNCT1(CONJUNCT2(REWRITE_RULE[EXTENSIONALLY_VALID_COMPONENT]
   E5_RF_COMPONENT_EXTENSIONALLY_VALID)));;
let E5_RF_CLEAR_IDENTITY = prove
 (e5_rf_clear_identity_statement,
  REPEAT STRIP_TAC THEN REWRITE_TAC[e5_rf_clear] THEN
  MP_TAC(SPEC `s:x86state` E5_RF_WRITE_READ) THEN ASM_REWRITE_TAC[]);;
let E5_RF_CLEAR_READ_FALSE = prove
 (`!s:x86state. ~bit 16(read rflags(e5_rf_clear s))`,
  REWRITE_TAC[e5_rf_clear;GSYM READ_BITELEMENT;GSYM READ_COMPONENT_COMPOSE] THEN
  CONV_TAC(TOP_DEPTH_CONV COMPONENT_READ_OVER_WRITE_CONV) THEN REWRITE_TAC[]);;
