let CLEANSE_ZERO_MEMORY_BYTES = prove
 (cleanse_zero_memory_bytes_statement,
  REWRITE_TAC[READ_BYTES; VAL_WORD_0; MULT_CLAUSES; NSUM_0]);;
let CLEANSE_READ_BYTES_ZERO = prove
 (cleanse_read_bytes_zero_statement,
  REPEAT GEN_TAC THEN
  MP_TAC(ISPECL [`m:int64->byte`; `\a:int64. word 0:byte`;
    `p:int64`; `n:num`] READ_BYTES_EQ) THEN
  REWRITE_TAC[CLEANSE_ZERO_MEMORY_BYTES]);;
let CLEANSE_PREFIX_ZERO_STORE_ELEMENT = prove
 (cleanse_prefix_zero_store_element_statement,
  REWRITE_TAC[CLEANSE_READ_BYTES_ZERO;
    REWRITE_RULE[READ_ELEMENT] READ_WRITE_ELEMENT] THEN
  REPEAT GEN_TAC THEN DISCH_TAC THEN X_GEN_TAC `j:num` THEN DISCH_TAC THEN
  ASM_CASES_TAC `j<i` THENL
   [COND_CASES_TAC THEN ASM_SIMP_TAC[];
    SUBGOAL_THEN `(j:num)=(i:num)` SUBST1_TAC THENL [ASM_ARITH_TAC; REWRITE_TAC[]]]);;
let CLEANSE_PREFIX_ZERO_STORE_BYTES8 = prove
 (cleanse_prefix_zero_store_bytes8_statement,
  REWRITE_TAC[BYTES8_ELEMENT; CLEANSE_PREFIX_ZERO_STORE_ELEMENT]);;
let CLEANSE_STATE_PREFIX_ZERO_STORE_BYTES8 = prove
 (cleanse_state_prefix_zero_store_bytes8_statement,
  REWRITE_TAC[READ_COMPONENT_COMPOSE; WRITE_COMPONENT_COMPOSE] THEN
  CONV_TAC(TOP_DEPTH_CONV COMPONENT_READ_OVER_WRITE_CONV) THEN
  REWRITE_TAC[CLEANSE_PREFIX_ZERO_STORE_BYTES8]);;
