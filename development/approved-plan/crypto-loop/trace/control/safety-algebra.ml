let CRYPTO_CONTROL_SPAN_HEAD = prove
 (`!rp p n. 0<n /\ assurance_span_ok rp (val(p:int64)) n
    ==> assurance_span_ok rp (val p) 1`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC ASSURANCE_SPAN_PREFIX THEN
  EXISTS_TAC `n:num` THEN ASM_REWRITE_TAC[] THEN ASM_ARITH_TAC);;
let CRYPTO_CONTROL_SPAN_TAIL = prove
 (`!rp p n. 0<n /\ assurance_span_ok rp (val(p:int64)) (SUC n)
    ==> assurance_span_ok rp (val(word_add p (word 1))) n`,
  REPEAT STRIP_TAC THEN
  SUBGOAL_THEN `val(p:int64)+1<2 EXP 64` ASSUME_TAC THENL
   [FIRST_X_ASSUM(MP_TAC o REWRITE_RULE[assurance_span_ok]) THEN ASM_ARITH_TAC;ALL_TAC] THEN
  SUBGOAL_THEN `val(word_add (p:int64) (word 1))=val p+1` SUBST1_TAC THENL
   [REWRITE_TAC[VAL_WORD_ADD;VAL_WORD;DIMINDEX_64] THEN CONV_TAC NUM_REDUCE_CONV THEN
    MATCH_MP_TAC MOD_LT THEN RULE_ASSUM_TAC(CONV_RULE NUM_REDUCE_CONV) THEN ASM_REWRITE_TAC[];ALL_TAC] THEN
  MATCH_MP_TAC ASSURANCE_SPAN_SUBRANGE THEN EXISTS_TAC `SUC n` THEN
  ASM_REWRITE_TAC[] THEN ARITH_TAC);;
